import { writeFile, unlink, mkdir } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { randomBytes } from "node:crypto";
import { runProcess } from "./process.mjs";
import "../backend/db.mjs";
export const projectRoot = fileURLToPath(new URL("../", import.meta.url));
export async function runMysqlTool(tool, args, { input, output } = {}) {
  const runtime = join(projectRoot, ".runtime");
  await mkdir(runtime, { recursive: true });
  const credentialFile = join(
    runtime,
    `client-${randomBytes(8).toString("hex")}.ini`,
  );
  // Passwords generated by bootstrap are hex; quoted custom values are escaped for option files.
  const escape = (x) =>
    String(x)
      .replaceAll("\\", "\\\\")
      .replaceAll('"', '\\"')
      .replaceAll("\n", "\\n");
  await writeFile(
    credentialFile,
    `[client]\nhost=${process.env.DB_HOST}\nport=${process.env.DB_PORT}\nuser=${process.env.DB_ADMIN_USER}\npassword="${escape(process.env.DB_ADMIN_PASSWORD)}"\n`,
    { mode: 0o600 },
  );
  const executable = process.platform === "win32" ? `${tool}.exe` : tool;
  const binary = process.env.MYSQL_BASE
    ? join(process.env.MYSQL_BASE, "bin", executable)
    : executable;
  try {
    await runProcess(
      binary,
      [`--defaults-extra-file=${credentialFile}`, ...args],
      { input, output },
    );
  } finally {
    await unlink(credentialFile);
  }
}
